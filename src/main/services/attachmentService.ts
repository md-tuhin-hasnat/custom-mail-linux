/**
 * attachmentService.ts
 * Service for attachment retrieval and filesystem downloads.
 * Fetches base64 payload from Gmail REST APIs or local mock fallback, formats data URLs for in-app media preview,
 * and launches native save dialogs for custom download path selection.
 */

import { app, dialog, BrowserWindow } from 'electron';
import fs from 'node:fs';
import path from 'node:path';
import { AccountConfig } from '../../types/account';
import { refreshGoogleToken } from './googleAuth';
import { StorageService } from './storageService';

